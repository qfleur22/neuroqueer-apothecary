const ratingItems = ({
  sectionId,
  texts,
}: {
  sectionId: string
  texts: string[]
}): EdsChecklistItem[] => {
  return texts.map((text, index) => {
    return {
      id: `${sectionId}-r${index + 1}`,
      text,
      kind: 'rating',
    }
  })
}

const noteItem = ({
  sectionId,
  text,
}: {
  sectionId: string
  text: string
}): EdsChecklistItem => {
  return {
    id: `${sectionId}-note`,
    text,
    kind: 'note',
  }
}

const promptItems = ({
  sectionId,
  texts,
}: {
  sectionId: string
  texts: string[]
}): EdsChecklistItem[] => {
  return texts.map((text, index) => {
    return {
      id: `${sectionId}-p${index + 1}`,
      text,
      kind: 'prompt',
    }
  })
}

const section = ({
  id,
  title,
  intro,
  ratings,
  note,
  prompts,
}: {
  id: string
  title: string
  intro?: string
  ratings?: string[]
  note?: string
  prompts?: string[]
}): EdsChecklistSection => {
  return {
    id,
    title,
    intro,
    items: [
      ...(ratings ? ratingItems({ sectionId: id, texts: ratings }) : []),
      ...(note ? [noteItem({ sectionId: id, text: note })] : []),
      ...(prompts ? promptItems({ sectionId: id, texts: prompts }) : []),
    ],
  }
}

